"""Write NOTES.md, the index of every note, from the notes' own titles.

    python shared/tools/index.py

wiki.py imports notes() from here so the wiki and the index always agree.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

GAMES = [
    ('games/t4-waw', 'WaW', 'World at War (T4)'),
    ('games/t5-bo1', 'BO1', 'Black Ops (T5)'),
    ('games/t6-bo2', 'BO2', 'Black Ops II (T6)'),
    ('games/t7-bo3', 'BO3', 'Black Ops III (T7)'),
    ('games/t8-bo4', 'BO4', 'Black Ops 4 (T8)'),
    ('games/iw4-mw2', 'MW2', 'Modern Warfare 2 (IW4)'),
    ('games/s1-aw', 'AW', 'Advanced Warfare (S1)'),
    ('shared', 'Shared', 'Cross-game'),
]
TOPICS = {
    'zombies': 'Zombies', 'mp': 'Multiplayer', 'engine': 'Engine', 'render': 'Rendering',
    'script': 'Scripting', 'assets': 'Assets and formats', 'world': 'World and collision', '': 'General',
}
TOPIC_ORDER = ['', 'zombies', 'mp', 'engine', 'render', 'script', 'assets', 'world']

HEADER = """# Notes index

<!-- generated by shared/tools/index.py from the notes' own titles; edit the notes, then rerun it -->

Every note in the repo, by game then topic. Each game folder also has a README that says what else is in it.

Most of these notes were written while building E115, our own engine that loads WaW, BO1 and BO2 content, and
Reforged, the game on top of it. Those two names turn up in the text. The notes are about the stock games, not
about E115.

No game files, script bodies, decompiled listings or string tables are in any note. Where a note depends on game
script it gives our own paraphrase or pseudocode plus the script file and function, so you can check it against your
own install. `<game install>`, `<export root>` and `<scratch>` stand for your own folders.

## Evidence marks

| Mark | Meaning |
| --- | --- |
| **[V]** | verified: read in the game's own code or data (script, exe, zone), usually with the place cited |
| **[M]** | measured: observed by running something (a probe, a dump, the game) |
| **[I]** | inferred: reasoned from the above, not directly checked |
| **[U]** | unknown: not in the data we have, or not yet found |
"""


def title(path):
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.startswith('# '):
            return line[2:].strip()
    return path.stem


def notes():
    """Yield (game dir, short label, long label, topic key, path relative to ROOT, title)."""
    for game, short, long in GAMES:
        base = ROOT / game
        files = sorted(base.glob('notes/**/*.md')) + sorted(p for p in base.glob('*.md') if p.name != 'README.md')
        for p in files:
            if p.name == 'README.md':
                continue
            rel = p.relative_to(base)
            topic = rel.parts[1] if len(rel.parts) > 2 and rel.parts[0] == 'notes' else ''
            yield game, short, long, topic, p.relative_to(ROOT).as_posix(), title(p)


def write_index():
    out = [HEADER]
    rows = list(notes())
    for game, short, long in GAMES:
        mine = [r for r in rows if r[0] == game]
        if not mine:
            continue
        out.append(f'\n## {long}\n')
        out.append(f'Folder: [`{game}/`]({game}/)\n')
        out.append('| Topic | Note | Title |\n| --- | --- | --- |')
        mine.sort(key=lambda r: (TOPIC_ORDER.index(r[3]), r[4]))
        for _, _, _, topic, rel, name in mine:
            out.append(f'| {TOPICS[topic]} | [{Path(rel).name}]({rel}) | {name} |')
    out.append('\nCredits for the tools and research behind these notes are in [CREDITS.md](CREDITS.md).\n')
    (ROOT / 'NOTES.md').write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print('wrote NOTES.md with', len(rows), 'notes')


if __name__ == '__main__':
    write_index()
