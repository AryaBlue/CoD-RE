r"""Mirror the notes to the GitHub wiki.

    python shared/tools/wiki.py            # write the pages into ../CoD-RE.wiki (a clone of the wiki repo)
    python shared/tools/wiki.py --push     # same, then commit and push
    python shared/tools/wiki.py D:\x\wiki  # write somewhere else

One-off setup: open the repo's Wiki tab on GitHub and press "Create the first page" (GitHub only creates the wiki
repo then), save anything, and clone it next to this repo:

    git clone https://github.com/AryaBlue/CoD-RE.wiki.git ../CoD-RE.wiki

Every note becomes one page named "<Game> <note name>", links between notes become wiki links, links to code and
tables point at the repo on GitHub. Home.md is the index, _Sidebar.md the per-game lists. The notes in the repo are
the source. Pages are rewritten every run, so never edit the wiki by hand.
"""
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from index import GAMES, HEADER, ROOT, TOPICS, TOPIC_ORDER, notes  # noqa: E402

REPO_URL = subprocess.run(['git', '-C', str(ROOT), 'remote', 'get-url', 'origin'], capture_output=True,
                          text=True, check=True).stdout.strip().removesuffix('.git')
BLOB = REPO_URL + '/blob/main/'
LINK = re.compile(r'\]\(([^)\s]+?)(#[^)]*)?\)')


def page_name(short, rel):
    stem = Path(rel).stem.replace('_', ' ')
    return f'{short} {stem}'


def page_file(name):
    return name.replace(' ', '-') + '.md'


def build(out):
    out.mkdir(parents=True, exist_ok=True)
    rows = list(notes())
    by_path = {rel: page_name(short, rel) for _, short, _, _, rel, _ in rows}
    assert len(set(by_path.values())) == len(by_path), 'two notes would get the same page name'
    written = set()

    for game, short, long, topic, rel, title in rows:
        src = ROOT / rel
        name = by_path[rel]
        text = src.read_text(encoding='utf-8')

        def sub(m, src=src):
            tgt, anchor = m.group(1), m.group(2) or ''
            if tgt.startswith(('#', 'http://', 'https://', 'mailto:')):
                return m.group(0)
            target = (src.parent / tgt).resolve()
            try:
                trel = target.relative_to(ROOT).as_posix()
            except ValueError:
                return m.group(0)
            if trel in by_path:
                return f']({page_file(by_path[trel])[:-3]}{anchor})'
            return f']({BLOB}{trel}{anchor})'

        text = LINK.sub(sub, text)
        banner = f'_Mirror of [`{rel}`]({BLOB}{rel}) in the CoD-RE repo. Edit it there, not here._\n\n'
        text = re.sub(r'^(# .*\n)', lambda m: m.group(1) + '\n' + banner, text, count=1)
        f = out / page_file(name)
        f.write_text(text, encoding='utf-8', newline='\n')
        written.add(f.name)

    home = [HEADER.replace('<!-- generated by shared/tools/index.py from the notes\' own titles; edit the notes, then rerun it -->\n\n', '')
            .replace('# Notes index', '# CoD-RE wiki')
            .replace('Every note in the repo, by game then topic. Each game folder also has a README that says what else is in it.',
                     f'Every note in the [CoD-RE repo]({REPO_URL}), by game then topic. This wiki is generated from the repo by '
                     f'`shared/tools/wiki.py`, so edit the notes there. The tools, headers and patches have READMEs in the repo: '
                     f'[WaW]({BLOB}games/t4-waw/README.md), [BO1]({BLOB}games/t5-bo1/README.md), [BO2]({BLOB}games/t6-bo2/README.md), '
                     f'[BO3]({BLOB}games/t7-bo3/README.md), [BO4]({BLOB}games/t8-bo4/README.md), [MW2]({BLOB}games/iw4-mw2/README.md), '
                     f'[converter]({BLOB}converter/README.md).')]
    sidebar = ['**[Home](Home)**', '']
    for game, short, long in GAMES:
        mine = sorted((r for r in rows if r[0] == game), key=lambda r: (TOPIC_ORDER.index(r[3]), r[4]))
        if not mine:
            continue
        home.append(f'\n## {long}\n')
        home.append('| Topic | Page | Title |\n| --- | --- | --- |')
        sidebar.append(f'<details><summary><b>{long}</b></summary>\n')
        for _, _, _, topic, rel, title in mine:
            link = page_file(by_path[rel])[:-3]
            home.append(f'| {TOPICS[topic]} | [{by_path[rel]}]({link}) | {title} |')
            sidebar.append(f'- [{by_path[rel]}]({link})')
        sidebar.append('\n</details>\n')
    home.append(f'\nCredits for the tools and research behind these notes: [CREDITS.md]({BLOB}CREDITS.md).\n')
    (out / 'Home.md').write_text('\n'.join(home), encoding='utf-8', newline='\n')
    (out / '_Sidebar.md').write_text('\n'.join(sidebar), encoding='utf-8', newline='\n')
    (out / '_Footer.md').write_text(
        f'Generated from [CoD-RE]({REPO_URL}) by `shared/tools/wiki.py`. No game files, only our notes. '
        f'[Credits]({BLOB}CREDITS.md)\n', encoding='utf-8', newline='\n')
    written |= {'Home.md', '_Sidebar.md', '_Footer.md'}
    for stale in out.glob('*.md'):
        if stale.name not in written:
            stale.unlink()
            print('removed stale', stale.name)
    print(f'wrote {len(written)} pages to {out}')


def push(out):
    sha = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
    git = lambda *a: subprocess.run(['git', '-C', str(out), *a], check=True)
    git('add', '-A')
    if subprocess.run(['git', '-C', str(out), 'diff', '--cached', '--quiet']).returncode == 0:
        print('wiki already up to date')
        return
    git('commit', '-q', '-m', f'sync notes from CoD-RE {sha}')
    git('push')


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    out = Path(args[0]) if args else ROOT.parent / 'CoD-RE.wiki'
    build(out)
    if '--push' in sys.argv:
        if not (out / '.git').exists():
            sys.exit(f'{out} is not a git clone of the wiki, see the top of this file')
        push(out)
